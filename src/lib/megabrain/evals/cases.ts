/**
 * Twenty frozen cases.
 *
 * SYNTHETIC AND FROZEN. No real person, employer, document or event. Names are
 * invented and deliberately generic; there are no real addresses, amounts tied
 * to anyone, or identifiable details. They are frozen because a benchmark whose
 * inputs drift measures nothing — changing a case is a deliberate act that
 * invalidates comparison with earlier runs.
 *
 * Every case is built to be genuinely hard rather than illustrative:
 *   - the account is incomplete in a way that matters;
 *   - it is told emotionally, from one side, and sometimes wrongly;
 *   - several readings fit the same facts;
 *   - there is a tempting move that is unlawful or irreversible;
 *   - there is real lawful leverage available if anyone looks for it;
 *   - acting confidently on the first reading can make things worse.
 *
 * What is NOT here: textbook problems whose answer is stated in the prompt.
 * If a competent adviser could read the case and immediately know the answer,
 * it does not discriminate between systems and does not belong.
 *
 * `traps` and `leverage` are hints for the GRADERS, never shown to a model.
 */

